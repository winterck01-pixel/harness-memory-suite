import test from 'node:test'
import assert from 'node:assert/strict'
import { TaskMemoryLedger } from '../lib/task-memory-ledger.js'
const ctx={session:'s',scope:'project:p',turn:'t1'}
const item={id:'m1',version:1,binding:'project:p'}
const make=()=>new TaskMemoryLedger()
const exposed=(l,c=ctx,i=item)=>l.expose({...c,items:[i]})[0]
test('opaque stable receipts bind exact session scope turn id and version',()=>{
 const l=make(), e=exposed(l)
 assert.equal(exposed(l).receipt,e.receipt)
 assert.match(e.receipt,/^[a-f0-9-]{36}$/)
 for(const patch of [{session:'other'},{scope:'other'},{turn:'other'},{id:'other'},{version:2},{receipt:'unknown'}]) assert.throws(()=>l.declare({...ctx,...e,reason:'used',...patch}))
 assert.throws(()=>l.declare({...ctx,id:'m1',version:1,reason:'used'}))
 assert.equal(l.status(ctx).declaredCount,0)
})
test('declarations and rejections are explicit idempotent local state without promotion',()=>{
 const l=make(),e=exposed(l),a={...ctx,...e,reason:'applied',callId:'c1'}
 assert.equal(l.declare(a).duplicate,false)
 assert.equal(l.declare(a).duplicate,true)
 assert.equal(l.declare({...a,callId:'c2'}).duplicate,true)
 assert.equal(l.reject({...a,reason:'wrong version'}).duplicate,false)
 assert.deepEqual(l.policy(ctx).suppressed,[{id:'m1',version:1}])
 assert.deepEqual(l.policy({session:'other',scope:ctx.scope}).suppressed,[])
 assert.equal(l.status(ctx).declaredCount,1)
 assert.equal('reason' in l.status(ctx),false)
})
test('new exposure turns invalidate earlier receipts, and retired turns cannot reactivate',()=>{
 const l=make(),e=exposed(l)
 exposed(l,{...ctx,turn:'t2'})
 assert.throws(()=>l.declare({...ctx,...e,reason:'old'}))
 assert.throws(()=>exposed(l,ctx))
})
test('outcomes describe runtime failures only and duplicate outcomes do not advance streak',()=>{
 const l=make(); exposed(l)
 l.outcome({...ctx,failed:true,toolError:true})
 l.outcome({...ctx,failed:true,toolError:true})
 assert.equal(l.policy(ctx).failureStreak,1)
 assert.throws(()=>l.outcome({...ctx,failed:false,success:true}))
 assert.throws(()=>l.outcome({...ctx,failed:false,toolError:false}))
 exposed(l,{...ctx,turn:'t2'});l.outcome({...ctx,turn:'t2',failed:false,toolError:false})
 assert.equal(l.policy(ctx).failureStreak,0)
})
test('trial summaries are truncated bounded transient metadata references',()=>{
 const l=make();exposed(l)
 for(let i=0;i<25;i++) l.trial({...ctx,text:'x'.repeat(1200),eventRef:`event:${i}`})
 const data=l.toJSON();assert.equal(data.sessions[0].trials.length,20)
 assert.equal(data.sessions[0].trials[0].text.length,1000)
 assert.equal(l.status(ctx).trialCount,20)
 assert.equal(JSON.stringify(l.status(ctx)).includes('xxxx'),false)
})
test('serialization preserves receipt isolation and idempotency and rejects untrusted extra fields',()=>{
 const l=make(),e=exposed(l),a={...ctx,...e,reason:'applied'};l.declare(a)
 const restored=TaskMemoryLedger.load(JSON.parse(JSON.stringify(l)))
 assert.equal(restored.declare(a).duplicate,true)
 assert.throws(()=>restored.declare({...a,session:'other'}))
 const bad=l.toJSON();bad.sessions[0].verified=true;assert.throws(()=>TaskMemoryLedger.load(bad))
 const bad2=l.toJSON();bad2.sessions[0].declarations[0].receipt='unknown';assert.throws(()=>TaskMemoryLedger.load(bad2))
})
test('strict input validation rejects unknown fields, missing scope, invalid types atomically',()=>{
 const l=make();for(const args of [{...ctx,items:[{...item,version:0}]},{...ctx,items:[item,{...item,id:''}]},{...ctx,scope:undefined,items:[item]},{...ctx,items:[item],verified:true}]) assert.throws(()=>l.expose(args))
 assert.equal(l.status(ctx).exposedCount,0)
 assert.throws(()=>l.status({session:'s'}))
 assert.throws(()=>l.trial({...ctx,text:'x',eventRef:''}))
})
test('configured bounds evict whole namespaces and exposure history safely',()=>{
 const l=new TaskMemoryLedger({maxSessions:2,maxExposuresPerSession:2,maxDeclarationsPerSession:2,maxTurnsPerSession:2})
 const old=exposed(l);exposed(l,{...ctx,session:'b'});exposed(l,{...ctx,session:'c'})
 assert.equal(l.status(ctx).exposedCount,0)
 assert.throws(()=>l.declare({...ctx,...old,reason:'expired'}))
 assert.equal(l.toJSON().sessions.length,2)
})
test('references only returns actual current exposures with no mutations',()=>{
 const l=make(),e=exposed(l)
 assert.deepEqual(l.references({...ctx,ids:['m1','missing']}),[e])
 assert.deepEqual(l.references({...ctx,session:'other',ids:['m1']}),[])
 assert.deepEqual(l.references({...ctx,turn:'other',ids:['m1']}),[])
 assert.equal(l.toJSON().sessions.length,1)
 assert.throws(()=>l.references({...ctx,ids:[undefined]}))
})
test('exposure caps preserve same-turn receipts and evictions produce loadable snapshots',()=>{
 const l=new TaskMemoryLedger({maxExposuresPerSession:2}),e=exposed(l)
 l.reject({...ctx,...e,reason:'avoid'})
 exposed(l,ctx,{...item,id:'m2'})
 assert.throws(()=>exposed(l,ctx,{...item,id:'m3'}))
 assert.equal(exposed(l).receipt,e.receipt)
 exposed(l,{...ctx,turn:'t2'},{...item,id:'m3'})
 const restored=TaskMemoryLedger.load(l.toJSON(),{maxExposuresPerSession:2})
 assert.equal(restored.status(ctx).exposedCount,2)
})
test('failed instance loads leave earlier valid evidence intact',()=>{
 const l=make(),e=exposed(l)
 assert.throws(()=>l.load({schemaVersion:1,sessions:[{session:'s'}]}))
 assert.deepEqual(l.references({...ctx,ids:['m1']}),[e])
 l.load(l.toJSON());assert.deepEqual(l.references({...ctx,ids:['m1']}),[e])
})
test('expired turn identifiers cannot resurrect older opaque receipts',()=>{
 const l=new TaskMemoryLedger({maxTurnsPerSession:1}),old=exposed(l)
 exposed(l,{...ctx,turn:'t2'})
 const fresh=exposed(l,ctx)
 assert.notEqual(fresh.receipt,old.receipt)
 assert.throws(()=>l.declare({...ctx,...old,reason:'replay'}))
 assert.doesNotThrow(()=>TaskMemoryLedger.load(l.toJSON(),{maxTurnsPerSession:1}))
})
test('trial hard cap applies across scopes in one session without exposing other scope contents',()=>{
 const l=make();exposed(l)
 for(let i=0;i<20;i++)l.trial({...ctx,text:'scope one',eventRef:`one:${i}`})
 const other={...ctx,scope:'project:other'};exposed(l,other)
 l.trial({...other,text:'scope two',eventRef:'two:0'})
 assert.equal(l.toJSON().sessions.reduce((n,s)=>n+s.trials.length,0),20)
 assert.equal(l.status(other).trialCount,1)
 assert.equal(l.status(ctx).trialCount,19)
 assert.doesNotThrow(()=>TaskMemoryLedger.load(l.toJSON()))
})
test('full declaration capacity rejects new actions atomically and preserves live rejection idempotency',()=>{
 const l=new TaskMemoryLedger({maxDeclarationsPerSession:1}),e=exposed(l),a={...ctx,...e,reason:'avoid this version'}
 l.reject(a)
 const before=l.toJSON()
 assert.throws(()=>l.declare({...a,reason:'used anyway'}),/declaration limit/i)
 assert.deepEqual(l.toJSON(),before)
 assert.deepEqual(l.policy(ctx).suppressed,[{id:item.id,version:item.version}])
 assert.equal(l.reject({...a,reason:'retry rejection',callId:'retry'}).duplicate,true)
 assert.deepEqual(l.toJSON(),before)
 const restored=TaskMemoryLedger.load(l.toJSON(),{maxDeclarationsPerSession:1})
 assert.equal(restored.reject(a).duplicate,true)
 assert.throws(()=>restored.declare({...a,reason:'used anyway'}),/declaration limit/i)
 assert.deepEqual(restored.policy(ctx).suppressed,[{id:item.id,version:item.version}])
})
test('new receipt action cannot evict rejection at declaration capacity',()=>{
 const l=new TaskMemoryLedger({maxDeclarationsPerSession:1}),e=exposed(l)
 l.reject({...ctx,...e,reason:'avoid'})
 const other=exposed(l,ctx,{...item,id:'m2'}),before=l.toJSON()
 assert.throws(()=>l.reject({...ctx,...other,reason:'avoid other'}),/declaration limit/i)
 assert.deepEqual(l.toJSON(),before)
 assert.equal(l.status(ctx).rejectedCount,1)
 assert.deepEqual(l.policy(ctx).suppressed,[{id:item.id,version:item.version}])
 assert.equal(l.reject({...ctx,...e,reason:'retry'}).duplicate,true)
})
test('late known-turn runtime outcome is independently idempotent without reactivating exposure receipts',()=>{
 const l=make(),old=exposed(l),next={...ctx,turn:'t2'}
 exposed(l,next)
 const before=l.toJSON().sessions[0]
 const args={...ctx,failed:true,toolError:false}
 assert.deepEqual(l.outcome(args),{ok:true,duplicate:false})
 assert.deepEqual(l.outcome(args),{ok:true,duplicate:true})
 assert.throws(()=>l.outcome({...args,failed:false}),/Conflicting runtime outcome/)
 const after=l.toJSON().sessions[0]
 assert.equal(after.currentTurn,'t2')
 assert.deepEqual(after.turns,before.turns)
 assert.deepEqual(after.exposures,before.exposures)
 assert.throws(()=>l.declare({...ctx,...old,reason:'late receipt replay'}))
 assert.deepEqual(l.references({...ctx,ids:[item.id]}),[])
 assert.doesNotThrow(()=>TaskMemoryLedger.load(l.toJSON()))
})
test('failure streak follows turn lifecycle rather than late outcome arrival order',()=>{
 const l=make();exposed(l)
 const second={...ctx,turn:'t2'};exposed(l,second)
 l.outcome({...second,failed:false,toolError:false})
 l.outcome({...ctx,failed:true,toolError:false})
 assert.equal(l.policy(ctx).failureStreak,0)
 const third={...ctx,turn:'t3'};exposed(l,third)
 l.outcome({...third,failed:true,toolError:true})
 assert.equal(l.policy(ctx).failureStreak,1)
 const restored=TaskMemoryLedger.load(l.toJSON())
 assert.equal(restored.policy(ctx).failureStreak,1)
 const fourth={...ctx,turn:'t4'};exposed(restored,fourth)

 assert.equal(restored.policy(ctx).failureStreak,1)
})
test('runtime outcome rejects unknown and evicted turns without mutating current lifecycle',()=>{
 const l=new TaskMemoryLedger({maxTurnsPerSession:1});exposed(l)
 exposed(l,{...ctx,turn:'t2'})
 const before=l.toJSON()
 for(const patch of [{turn:'unknown'},{turn:'t1'},{session:'missing'},{scope:'missing'}]){
  assert.throws(()=>l.outcome({...ctx,failed:true,toolError:false,...patch}),/Unknown runtime outcome turn/)
  assert.deepEqual(l.toJSON(),before)
 }
})
test('late outcome arrival cannot evict a retained newer outcome when lifecycle capacity rotates',()=>{
 const l=new TaskMemoryLedger({maxTurnsPerSession:2});exposed(l)
 const second={...ctx,turn:'t2'};exposed(l,second)
 l.outcome({...second,failed:true,toolError:false})
 l.outcome({...ctx,failed:false,toolError:false})
 const third={...ctx,turn:'t3'};exposed(l,third)
 l.outcome({...third,failed:true,toolError:false})
 assert.equal(l.policy(ctx).failureStreak,2)
 assert.equal(l.outcome({...second,failed:true,toolError:false}).duplicate,true)
 assert.equal(TaskMemoryLedger.load(l.toJSON(),{maxTurnsPerSession:2}).policy(ctx).failureStreak,2)
})
test('empty turns expire all old turn evidence at lifecycle capacity and preserve loadable snapshots',()=>{
 const options={maxTurnsPerSession:2},l=new TaskMemoryLedger(options),old=exposed(l)
 l.reject({...ctx,...old,reason:'avoid'})
 l.outcome({...ctx,failed:true,toolError:false})
 l.trial({...ctx,text:'trial summary',eventRef:'event:t1'})
 for(const turn of ['t2','t3','t4']){
  l.expose({...ctx,turn,items:[]})
  assert.doesNotThrow(()=>TaskMemoryLedger.load(l.toJSON(),options))
 }
 const s=l.toJSON().sessions[0]
 assert.deepEqual(s.turns,['t3','t4'])
 for(const name of ['exposures','declarations','outcomes','trials'])assert.deepEqual(s[name],[])
 assert.deepEqual(l.policy(ctx).suppressed,[])
 assert.equal(l.policy(ctx).failureStreak,0)
 assert.throws(()=>l.declare({...ctx,...old,reason:'expired'}))
 assert.throws(()=>l.outcome({...ctx,failed:true,toolError:false}),/Unknown runtime outcome turn/)
})
